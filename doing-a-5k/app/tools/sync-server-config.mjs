#!/usr/bin/env node
/* Writes supabase/functions/_shared/ladder-config.ts in the PRIVATE backend repo (sosacleans-pixel/achallengetomove-backend)
 * from doing-a-5k/app/js/ladder/config.js, so the edge functions use the same Stripe price IDs, prices, access lengths,
 * level IDs and customer-facing level names as the app.
 * Usage: node doing-a-5k/app/tools/sync-server-config.mjs [--check] [--print]
 *   BACKEND_DIR = path of the backend checkout (default: a sibling folder named achallengetomove-backend)
 *   --check exits 1 if the file is stale (skips with a note when the backend checkout is not present)
 *   --print writes the generated file to stdout instead (used by the tests) */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const C = await import(join(here, "../js/ladder/config.js"));
const index = JSON.parse(readFileSync(join(here, "../data/ladder/index.json"), "utf8"));
const cfg = {
  app: "achallengetomove-running-plans",
  levels: Object.keys(C.STRIPE_IDS),
  stripe: C.STRIPE_IDS,
  priceCents: Object.fromEntries(Object.entries(C.PRICES).map(([k, v]) => [k, Math.round(Number(v) * 100)])),
  accessWeeksByDays: C.ACCESS_WEEKS_BY_DAYS,
  giftCodeYears: index.giftCodeRedeemableYears,
  headStartCoreIndex: index.placementStarts["walk-to-5k-from-week-6"].startCoreIndex,
  timeZone: "America/Denver",
  siteUrl: C.SERVER.siteUrl,
  levelNames: C.NAMES.levels,
  redeemUrl: `${C.SERVER.siteUrl}/doing-a-5k/app/#l-redeem?code=`,
  stopUrl: `${C.SERVER.siteUrl}/doing-a-5k/app/#l-stop`,
  returnUrls: {
    purchase: `${C.SERVER.siteUrl}/doing-a-5k/app/#l-paid?session_id={CHECKOUT_SESSION_ID}`,
    gift: `${C.SERVER.siteUrl}/doing-a-5k/app/#l-gift-status?session_id={CHECKOUT_SESSION_ID}&new=1`,
    cancel: `${C.SERVER.siteUrl}/doing-a-5k/`,
  },
};
const out = `// GENERATED by doing-a-5k/app/tools/sync-server-config.mjs from doing-a-5k/app/js/ladder/config.js. Do not edit.
// Stripe IDs only, never keys.
export const LADDER = ${JSON.stringify(cfg, null, 2)} as const;
`;
if (process.argv.includes("--print")) { process.stdout.write(out); process.exit(0); }
const backend = resolve(process.env.BACKEND_DIR || join(root, "../achallengetomove-backend"));
const file = join(backend, "supabase/functions/_shared/ladder-config.ts");
if (!existsSync(join(backend, "supabase/functions/_shared"))) {
  console.log(`backend checkout not found at ${backend}; set BACKEND_DIR to check or write ladder-config.ts`);
  process.exit(0);
}
let cur = "";
try { cur = readFileSync(file, "utf8"); } catch {}
if (process.argv.includes("--check")) {
  if (cur !== out) { console.error(`${file} is stale: run node doing-a-5k/app/tools/sync-server-config.mjs`); process.exit(1); }
  console.log("ladder-config.ts is in sync.");
} else {
  writeFileSync(file, out);
  console.log(`wrote ${file}`);
}
