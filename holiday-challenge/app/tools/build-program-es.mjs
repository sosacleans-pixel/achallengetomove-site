// Builds js/program.es.js from js/program.en.js + tools/program-es-map.json (English text -> Latin American Spanish).
// Run: node tools/build-program-es.mjs   (fails if any display string has no translation)
// Codes, ids, dates, weekday keys, categories and week keys are kept as-is so the app logic is unchanged.
import { readFileSync, writeFileSync } from "fs";
import { PROGRAM } from "../js/program.en.js";
const dir = new URL("..", import.meta.url);
const map = JSON.parse(readFileSync(new URL("tools/program-es-map.json", dir), "utf8"));
const KEEP = new Set(["id", "version", "date", "wd", "cat", "week", "start", "end", "retestWindow", "protectedExtendUntil"]);
const missing = new Set();
const sub = (s) => s.replace(/(\d) ?s\/side/g, "$1 s/lado").replace(/(\d)\/side/g, "$1/lado");
function tr(v, key, idx) {
  if (typeof v === "string") {
    if (KEEP.has(key) || idx === 0) return v;
    if (map[v] != null) return map[v];
    if (/^[\d\s.+\-–/x×]*(s|min)?$/.test(v) || /^\d[\d\s\-]*(s|min)?( s\/side| ?\/side)?$/.test(v) || /^(RPE )?[\d\- ]+$/.test(v)) return sub(v);
    missing.add(v); return v;
  }
  if (Array.isArray(v)) return v.map((x, i) => tr(x, key, i));
  if (v && typeof v === "object") { const o = {}; for (const k in v) o[k] = KEEP.has(k) ? v[k] : tr(v[k], k, -1); return o; }
  return v;
}
const ES = tr(PROGRAM, "", -1);
ES.lang = "es";
if (missing.size) { console.error("Missing translations:\n" + [...missing].join("\n")); process.exit(1); }
writeFileSync(new URL("js/program.es.js", dir), `// GENERATED by tools/build-program-es.mjs from program.en.js + tools/program-es-map.json. Do not edit by hand.\n// Spanish (Latin America) program content. Same shape, codes and dates as program.en.js.\nexport const PROGRAM = ${JSON.stringify(ES)};\n`);
console.log("wrote js/program.es.js");
